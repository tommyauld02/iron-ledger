"""The iPhone app's shell version, and the guard that keeps it honest.

A live update replaces the app's web files on phones that already have the app
(docs/ios.md, "How an update reaches phones"). It cannot add a plugin, a
permission or anything else in the native shell — those need a store build.
So every live update says which shell it needs: the shell's version,
MARKETING_VERSION in the Xcode project, which is the one place it is set.
A phone whose shell is older ignores the update.

That only works if the version goes up whenever the shell changes. This file
fingerprints everything that makes up the shell and keeps a ledger,
ios/shell-versions.json, of the fingerprint each version was released with.
tests/live.py fails if the shell has changed but the version has not.

    python tools/shell-version.py            what the shell is, and whether it is recorded
    python tools/shell-version.py --record   record it, after raising MARKETING_VERSION in Xcode
"""
import hashlib, io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PBXPROJ = os.path.join("ios", "App", "App.xcodeproj", "project.pbxproj")
LEDGER = os.path.join("ios", "shell-versions.json")
# Lines of the project file that change with every build or every person, and
# say nothing about what the shell can do.
VOLATILE = re.compile(r"^\s*(MARKETING_VERSION|CURRENT_PROJECT_VERSION|DEVELOPMENT_TEAM) = ")


def marketing_version(root=ROOT):
    found = set(re.findall(r"MARKETING_VERSION = ([^;]+);",
                           io.open(os.path.join(root, PBXPROJ), encoding="utf-8").read()))
    if len(found) != 1:
        raise SystemExit("MARKETING_VERSION differs between the project's configurations: %s" % sorted(found))
    return found.pop().strip().strip('"')


def _text(path):
    # Windows checkouts turn LF into CRLF; the fingerprint must not notice.
    return io.open(path, encoding="utf-8").read().replace("\r\n", "\n").encode("utf-8")


def shell_files(root=ROOT):
    """Every file that makes up the shell, as (name, bytes), in a fixed order."""
    out = []
    pkg = json.load(io.open(os.path.join(root, "package.json"), encoding="utf-8"))
    out.append(("package.json#dependencies", json.dumps(pkg.get("dependencies", {}), sort_keys=True).encode()))
    cfg = json.load(io.open(os.path.join(root, "capacitor.config.json"), encoding="utf-8"))
    out.append(("capacitor.config.json", json.dumps(cfg, sort_keys=True).encode()))
    proj = _text(os.path.join(root, PBXPROJ)).decode("utf-8")
    out.append((PBXPROJ, "\n".join(l for l in proj.split("\n") if not VOLATILE.match(l)).encode("utf-8")))
    for base in (os.path.join("ios", "App", "App"), os.path.join("ios", "App", "CapApp-SPM")):
        for d, dirs, files in os.walk(os.path.join(root, base)):
            dirs[:] = sorted(x for x in dirs if x != "public")      # public/ is the web app, copied in
            for f in sorted(files):
                rel = os.path.relpath(os.path.join(d, f), root)
                if f in ("capacitor.config.json", "config.xml", ".DS_Store"):   # generated by cap sync
                    continue
                full = os.path.join(root, rel)
                data = io.open(full, "rb").read() if f.endswith(".png") else _text(full)
                out.append((rel.replace(os.sep, "/"), data))
    return out


def fingerprint(root=ROOT):
    h = hashlib.sha256()
    for name, data in shell_files(root):
        h.update(name.encode("utf-8") + b"\0" + hashlib.sha256(data).hexdigest().encode() + b"\n")
    return h.hexdigest()


def ledger(root=ROOT):
    p = os.path.join(root, LEDGER)
    return json.load(io.open(p, encoding="utf-8")) if os.path.exists(p) else {}


if __name__ == "__main__":
    v, fp, led = marketing_version(), fingerprint(), ledger()
    print("shell %s  fingerprint %s" % (v, fp[:16]))
    if "--record" in sys.argv:
        if v in led and led[v] != fp:
            raise SystemExit("Version %s was released with a different shell. Raise MARKETING_VERSION "
                             "in Xcode (both configurations) first, then record again." % v)
        led[v] = fp
        io.open(os.path.join(ROOT, LEDGER), "w", encoding="utf-8", newline="\n").write(
            json.dumps(led, indent=2, sort_keys=True) + "\n")
        print("recorded in " + LEDGER.replace(os.sep, "/"))
    else:
        print("recorded" if led.get(v) == fp else
              "NOT recorded: the shell has changed since %s was recorded" % v if v in led else
              "NOT recorded: run with --record")
