"""Build the restaurant menus from each chain's own published nutrition.

Step 4 of the one-stop shop: "I had a Big Mac, medium fries and a Coke" should
be three taps, from numbers the chain itself publishes, with no internet at the
table. USDA's fast-food group is from 2018 and chains change recipes, so these
come from the chains: their nutrition pages and PDFs, read on the date each
file says. The sources are kept as plain text in tools/menus/, one file per
chain, so anyone can check a number against where it came from.

    python tools/make-menus.py

Each tools/menus/<chain>.txt starts with a comment naming the chain and its
source ("# Chick-fil-A — https://... — read 2026-10-13"); any further comment
lines are notes shown with the chain. Then one line per menu item:

    group|item|option~grams~kcal~protein~carbs~fat;option~...

An item with no options is written "0~kcal~protein~carbs~fat" with grams 0.
Grams of 0 mean the chain did not state a weight. Nothing is estimated: an item
is either as the chain published it or added up from parts the chain published,
and an added-up one says so in its name.

Writes vendor/menus/menus.js, a script setting window.IRON_LEDGER_MENUS, for
the same reason foods.js is one: a page opened from disk cannot fetch().
"""
import glob, io, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "menus")
OUT = os.path.join(ROOT, "vendor", "menus", "menus.js")


def clean(s):
    s = s.replace("®", "").replace("™", "").replace("&trade", "")
    return " ".join(s.split())


def short_option(opt, item):
    """"Medium Chick-fil-A Waffle Potato Fries" under "Chick-fil-A Waffle Potato
    Fries" is "Medium"; "8 ct Chick-fil-A Nuggets" is "8 ct"."""
    o, it = clean(opt), clean(item)
    if it and it.lower() in o.lower() and o.lower() != it.lower():
        i = o.lower().index(it.lower())
        rest = (o[:i] + " " + o[i + len(it):]).strip()
        rest = re.sub(r"^w/\s*", "with ", rest)
        rest = re.sub(r"\s+", " ", rest).strip(" ,-")
        if rest:
            return rest[0].upper() + rest[1:]
    return o


def num(s):
    s = s.strip()
    v = float(s)
    return int(v) if v == int(v) else v


def read(path):
    head, notes, groups, order = None, [], {}, []
    for line in io.open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip():
            continue
        if line.startswith("#"):
            text = line.lstrip("#").strip()
            if head is None:
                head = text
            elif not text.startswith("group|"):
                notes.append(text)
            continue
        group, item, rest = line.split("|", 2)
        opts = []
        for part in rest.split(";"):
            f = part.split("~")
            if len(f) == 5:
                f = [""] + f
            assert len(f) == 6, (path, line)
            name, g, k, p, c, fa = f[0], num(f[1]), num(f[2]), num(f[3]), num(f[4]), num(f[5])
            if name == "0":
                name = ""                      # a lone item with its weight: "0~grams~kcal~..."
            assert 0 <= k <= 3000 and 0 <= p <= 200 and 0 <= c <= 400 and 0 <= fa <= 200, (path, line)
            # calories should be roughly what the macros add up to; a typo in a
            # copied number shows up here rather than on someone's day
            if k >= 100:
                atwater = 4 * p + 4 * c + 9 * fa
                assert 0.6 * k <= atwater <= 1.45 * k, ("macros do not add up", path, line, atwater)
            opts.append([short_option(name, item) if name else "", g, k, p, c, fa])
        if group not in groups:
            groups[group] = []
            order.append(group)
        groups[group].append([clean(item), opts])
    parts = [x.strip() for x in re.split(r"\s+—\s+", head)]
    name, src = parts[0], " — ".join(parts[1:-1]) if len(parts) > 2 else (parts[1] if len(parts) > 1 else "")
    when = re.search(r"read (\d{4}-\d{2}-\d{2})", head)
    return {
        "id": os.path.splitext(os.path.basename(path))[0],
        "name": re.sub(r"\s*\(US\)$", "", clean(name)),
        "src": src,
        "read": when.group(1) if when else "",
        "notes": notes,
        "groups": [[g, groups[g]] for g in order],
    }


def main():
    chains = [read(p) for p in sorted(glob.glob(os.path.join(SRC, "*.txt")))]
    chains.sort(key=lambda c: c["name"].lower())
    lib = {
        "about": "Each chain's own published nutrition, read on the date given. "
                 "Generated by tools/make-menus.py from tools/menus/; do not edit by hand.",
        "chains": chains,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with io.open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/make-menus.py from tools/menus/. Do not edit. */\n")
        fh.write("window.IRON_LEDGER_MENUS=")
        json.dump(lib, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")
    n = sum(len(i[1]) for c in chains for g in c["groups"] for i in g[1])
    print("wrote %s: %d chains, %d items, %.1f KB" % (os.path.relpath(OUT, ROOT), len(chains), n,
                                                       os.path.getsize(OUT) / 1e3))


if __name__ == "__main__":
    main()
